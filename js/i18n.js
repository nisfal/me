function getCurrentPageKey() {
  const page = window.location.pathname.split('/').pop() || 'index.html';
  if (page.includes('backend')) return 'backend';
  if (page.includes('frontend')) return 'frontend';
  if (page.includes('profile') || page.includes('c-137')) return 'profile';
  if (page.includes('404')) return 'not_found';
  return 'home';
}

function getInitialLanguage() {
  const params = new URLSearchParams(window.location.search);
  const langFromUrl = params.get('lang');
  if (langFromUrl && I18N_DICTIONARY[langFromUrl]) return langFromUrl;
  const saved = localStorage.getItem('portfolio_language');
  if (saved && I18N_DICTIONARY[saved]) return saved;
  const browserLanguage = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
  return browserLanguage.startsWith('id') ? 'id' : 'en';
}

function updateLanguageLinks(lang) {
  document.querySelectorAll('a[href]').forEach((link) => {
    const href = link.getAttribute('href');
    if (!href || href.startsWith('http') || href.startsWith('mailto:') || href.startsWith('tel:') || href.startsWith('javascript:')) return;
    if (href.startsWith('#')) return;

    // Check if it's an internal page route (supports both clean URLs and .html)
    const isInternalPage = href.includes('.html') ||
      href === '/' || href.startsWith('/?') || href.startsWith('/#') ||
      href === 'backend' || href.startsWith('backend?') || href.startsWith('backend#') ||
      href === 'frontend' || href.startsWith('frontend?') || href.startsWith('frontend#') ||
      href === 'profile' || href.startsWith('profile?') || href.startsWith('profile#') ||
      href === 'c-137' || href.startsWith('c-137?') || href.startsWith('c-137#') ||
      href === 'index' || href.startsWith('index?') || href.startsWith('index#');

    if (!isInternalPage) return;

    const [pathWithQuery, hash = ''] = href.split('#');
    const [path] = pathWithQuery.split('?');
    link.setAttribute('href', `${path}?lang=${lang}${hash ? `#${hash}` : ''}`);
  });
}

function updateSeo(lang, dictionary) {
  const pageKey = getCurrentPageKey();
  const title = dictionary[`meta_title_${pageKey}`];
  const description = dictionary[`meta_desc_${pageKey}`];
  if (title) document.title = title;
  const metaDescription = document.querySelector('meta[name="description"]');
  if (metaDescription && description) metaDescription.setAttribute('content', description);
  const canonical = document.querySelector('link[rel="canonical"]');
  if (canonical) canonical.setAttribute('href', `${window.location.origin}${window.location.pathname}`);
  document.querySelectorAll('link[rel="alternate"][hreflang]').forEach((link) => {
    const hreflang = link.getAttribute('hreflang');
    const language = hreflang === 'id' ? 'id' : 'en';
    link.setAttribute('href', `${window.location.origin}${window.location.pathname}?lang=${language}`);
  });
}

function getDictValue(dict, key) {
  if (!dict || !key) return undefined;
  if (dict[key] !== undefined) return dict[key];
  return key.split('.').reduce((obj, part) => (obj && obj[part] !== undefined ? obj[part] : undefined), dict);
}

function setLanguage(lang) {
  const dictionary = I18N_DICTIONARY[lang] || I18N_DICTIONARY.en;
  document.documentElement.lang = lang;
  localStorage.setItem('portfolio_language', lang);
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.getAttribute('data-i18n');
    const val = getDictValue(dictionary, key);
    if (val !== undefined) element.innerHTML = val;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.getAttribute('data-i18n-placeholder');
    const val = getDictValue(dictionary, key);
    if (val !== undefined) element.setAttribute('placeholder', val);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((element) => {
    const key = element.getAttribute('data-i18n-title');
    const val = getDictValue(dictionary, key);
    if (val !== undefined) element.setAttribute('title', val);
  });
  document.querySelectorAll('[data-lang-option]').forEach((button) => {
    const isActive = button.getAttribute('data-lang-option') === lang;
    button.classList.toggle('active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });
  updateLanguageLinks(lang);
  updateSeo(lang, dictionary);
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('[data-lang-option]').forEach((button) => {
    button.addEventListener('click', () => {
      const lang = button.getAttribute('data-lang-option');
      setLanguage(lang);
      const url = new URL(window.location.href);
      url.searchParams.set('lang', lang);
      window.history.replaceState({}, '', url);
    });
  }); 
  setLanguage(getInitialLanguage());
});